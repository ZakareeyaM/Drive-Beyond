#!/usr/bin/env python3
"""Generates scripts/vehicles/fleet_vehicles.gd from the measured fleet GLBs (tools/fleet_probe.gd -> JSON) + the per-car gameplay table below."""
import json, sys
probe = json.load(open(sys.argv[1]))
# id: (name, cat, price, mass, accel, top, brake, steer, grip, stiff, drive, gears, final, engine, redline, turbo, roll, tank, paint_rgb, extra, headlight)
CARS = [
 ("countach","Lamborghini Countach 25th Anniversary","Supercar",165000,1490,7.0,76,10.4,0.54,3.7,50,"RWD",[3.1,2.0,1.45,1.12,0.9],3.5,"v12",7800,False,0.14,120,(0.74,0.75,0.77),{},{}),
 ("m3_gtr","BMW M3 E46 GTR","Sports Car",54000,1500,6.8,70,11.2,0.6,4.0,48,"RWD",[3.3,2.1,1.5,1.12,0.88],3.6,"i6",8000,False,0.15,62,(0.62,0.64,0.68),{},{}),
 ("sesto","Lamborghini Sesto Elemento SCPD","Supercar",210000,1000,9.2,90,13.0,0.56,4.6,58,"AWD",[3.0,2.0,1.5,1.2,0.98,0.8],3.4,"v10",8600,False,0.1,90,(0.5,0.5,0.5),{},{}),
 ("nsx","Honda NSX LB Works","Sports Car",72000,1400,7.4,76,11.8,0.62,4.1,50,"RWD",[3.2,2.1,1.5,1.15,0.92],3.6,"v6",8000,False,0.13,70,(0.93,0.93,0.94),{},{}),
 ("gclass","Mercedes-AMG G 63","SUV",92000,2500,5.4,60,8.8,0.5,3.4,56,"AWD",[3.5,2.2,1.5,1.05,0.8,0.65],3.6,"v8",6200,True,0.26,100,(0.41,0.42,0.33),{"offroad":True,"susp":0.34},{"y_off":0.0,"pitch":-6.0}),
 ("mustang","Ford Mustang GTD","Muscle Car",98000,1750,8.2,82,11.5,0.55,4.2,52,"RWD",[3.0,2.0,1.45,1.05,0.8],3.4,"v8",7600,True,0.17,68,(0.46,0.49,0.5),{},{}),
 ("amg_one","Mercedes-AMG ONE","Hypercar",480000,1400,11.5,104,15.0,0.52,5.2,64,"AWD",[2.9,2.0,1.55,1.25,1.02,0.85,0.7],3.4,"v6",11000,True,0.08,60,(0.9,0.9,0.92),{},{}),
]
def f(x): return ("%.3f" % x).rstrip("0").rstrip(".") if abs(x) > 1e-9 else "0"
out = ["class_name FleetVehicles", "extends RefCounted",
"## GENERATED by tools/gen_fleet_vehicles.py from the converted GLBs in assets/vehicles/fleet/ (made by tools/prepare_fleet.gd).",
"## Each entry: gameplay spec (Data.VEHICLES) + measured model data (VehicleModels / GlbVehicle) + per-vehicle headlight overrides.",
"","const LIST := ["]
for (id,name,cat,price,mass,acc,top,brk,steer,grip,stiff,drive,gears,final,eng,red,turbo,roll,tank,prgb,extra,hl) in CARS:
    p = probe[id]
    w = p["wheels"]
    wy = sum(x[1] for x in w)/4
    track = (abs(w[0][0])+abs(w[1][0])+abs(w[2][0])+abs(w[3][0]))/2
    track = abs(w[1][0]-w[0][0])*0.5 + abs(w[3][0]-w[2][0])*0.5
    wb = ((w[2][2]+w[3][2])-(w[0][2]+w[1][2]))/2
    L = p["zmax"]-p["zmin"]; H = p["ymax"]; W = p["width"]
    spec = {"id":id,"name":name,"cat":cat,"price":price,"mass":float(mass),"accel":acc,"top":float(top),"brake":brk,"steer":steer,"grip":grip,"stiff":float(stiff),"drive":drive,"gears":gears,"final":final,"engine":eng,"redline":float(red),"turbo":turbo,"roll":roll,"wr":round(wy,3),"ww":round(p["ww"],3),"L":round(L,2),"W":round(W,2),"belly":0.14,"hood":round(H*0.55,2),"belt":round(H*0.62,2),"trunk":round(H*0.6,2),"roof":round(H,2),"cab0":0.3,"cab1":0.85,"roof0":0.4,"roof1":0.8,"wb":round(wb,3),"track":round(track,3),"paint":4,"offroad":False,"ai":14.0,"tank":float(tank),"fleet":True}
    spec.update(extra)
    model = {"zmin":round(p["zmin"],3),"zmax":round(p["zmax"],3),"height":round(H,3),"width":round(W,3),"paint_rgb":list(prgb)}
    def gd(v):
        if isinstance(v,bool): return "true" if v else "false"
        if isinstance(v,str): return '"%s"'%v
        if isinstance(v,(list,tuple)): return "["+", ".join(gd(x) for x in v)+"]"
        if isinstance(v,dict): return "{"+", ".join('"%s": %s'%(k,gd(x)) for k,x in v.items())+"}"
        return f(v) if isinstance(v,float) else str(v)
    out.append('\t{"spec": %s,\n\t "model": %s,\n\t "headlight": %s},' % (gd(spec), gd(model), gd(hl)))
out.append("]")
open("scripts/vehicles/fleet_vehicles.gd","w").write("\n".join(out)+"\n")
